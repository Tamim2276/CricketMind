"""The LaTeX tables the paper uses, written straight from measured rows.

Only the tabular is written. The caption stays in the paper, where it can be
edited freely; the numbers stay here, where they are measured. The paper must
load booktabs (for the rules) and array (for the wrapped columns).
"""
from ..agents import AGENTS_BY_ID, agent_name
from ..config import PROJECT_ROOT
from .profile import PAPER_ROW_NAMES
from .routing_eval import (FLOW_STAGES, ROUTING_PROMPTS, describe_write,
                           prompt_style_counts)

TABLES_DIR = PROJECT_ROOT / "paper" / "CricketMind_ICCIT" / "tables"
GENERATED_BY = [
    "% Generated by notebooks/02_results.ipynb via cricketmind.experiments.tables.",
    "% Do not edit by hand -- re-run the notebook instead.",
]


def latex_escape(text: str) -> str:
    r"""Make plain text safe inside a LaTeX table: & % $ # _ { } ~ ^ \ are special."""
    special = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
               "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
               "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(special.get(ch, ch) for ch in str(text))


def _write(lines: list, path) -> str:
    text = "\n".join(lines) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text


def write_cost_table(rows: list, path=None) -> str:
    """The execution-profile table: one row per scenario, measured."""
    path = path or TABLES_DIR / "tab_execution_profile.tex"
    by_name = {r["scenario"]: r for r in rows}

    lines = GENERATED_BY + [
        r"\begin{tabular}{@{}lrrrrr@{}}",
        r"\toprule",
        r"Scenario & $r$ & $g$ & Steps & \shortstack{Node\\runs} & \shortstack{Agent\\calls} \\",
        r"\midrule",
    ]
    for notebook_name, paper_name in PAPER_ROW_NAMES.items():
        r = by_name[notebook_name]
        lines.append(f"{paper_name} & {r['retries']} & {r['regens']} & {r['steps']} & "
                     f"{r['node_runs']} & {r['agent_calls']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(lines, path)


def write_routing_summary(per_run: dict, stable: list, seconds: list, path=None) -> str:
    """The keyword-vs-LLM summary table.

    per_run maps a `compare()` label to (keyword values, LLM values -- one per
    run). If the LLM runs disagree, the cell shows the range, e.g. "8/12--9/12".
    """
    path = path or TABLES_DIR / "tab_routing_summary.tex"
    styles = prompt_style_counts()
    rows = [   # (label from compare(), label in the paper, denominator -- None for a mean)
        ("keyword prompts, target woken by the router",
         "Keyword prompts: target activated", styles["keyword"]),
        ("plain prompts, target woken by the router",
         "Plain prompts: target activated", styles["plain"]),
        ("prompts that fell back to the default pair",
         "Fell back to the default agents", len(ROUTING_PROMPTS)),
        ("agents woken per prompt (mean)",
         "Agents activated per prompt (mean)", None),
    ]
    n_runs = len(per_run[rows[0][0]][1])

    lines = GENERATED_BY + [
        r"\begin{tabular}{@{}lrr@{}}",
        r"\toprule",
        r" & Keyword & LLM \\",
        r"\midrule",
    ]
    for key, label, den in rows:
        cells = []
        for values in per_run[key]:
            lo, hi = min(values), max(values)
            a, b = (f"{lo:.2f}", f"{hi:.2f}") if den is None else (f"{lo}/{den}", f"{hi}/{den}")
            cells.append(a if lo == hi else f"{a}--{b}")
        lines.append(f"{label} & {cells[0]} & {cells[1]} \\\\")
    lines.append(f"Identical routing in all {n_runs} runs & -- & {sum(stable)}/{len(stable)} \\\\")
    lines.append(f"Routing time per prompt (mean) & -- & {sum(seconds) / len(seconds):.1f}\\,s \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(lines, path)


def write_plain_table(llm_rows: list, path=None) -> str:
    """One row per plain prompt: who it was written for, the question, and the
    agents the LLM router activated. The target is bold when the router chose
    it; "(default)" marks a fall-back to the default agents.
    """
    path = path or TABLES_DIR / "tab_routing_plain.tex"
    by_id = {r["id"]: r for r in llm_rows}
    col = r">{\raggedright\arraybackslash}p"

    lines = GENERATED_BY + [
        rf"\begin{{tabular}}{{@{{}}l{col}{{0.52\textwidth}}{col}{{0.30\textwidth}}@{{}}}}",
        r"\toprule",
        r"Written for & Plain question (no trigger words) & LLM router activated \\",
        r"\midrule",
    ]
    for p in ROUTING_PROMPTS:
        if p["style"] != "plain":
            continue
        r = by_id[p["id"]]
        names = []
        for a in r["woken"]:
            name = latex_escape(agent_name(a))
            chosen_target = a == p["target"] and r["target_woken"] == "signal"
            names.append(rf"\textbf{{{name}}}" if chosen_target else name)
        default = " (default)" if all(w == "default" for w in r["why"].values()) else ""
        lines.append(f"{latex_escape(agent_name(p['target']))} & "
                     f"{latex_escape(p['prompt'])} & {', '.join(names)}{default} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(lines, path)


def write_flow_table(flow_writes: dict, path=None, stages=None) -> str:
    """The two queries, stage by stage, as a LaTeX table.

    Each cell is what that stage wrote for that question -- describe_write's
    line, except that agents list every figure they cite.
    """
    path = path or TABLES_DIR / "tab_prompt_flow.tex"
    col = r">{\raggedright\arraybackslash}p"
    labels = list(flow_writes)

    lines = GENERATED_BY + [
        rf"\begin{{tabular}}{{@{{}}{col}{{0.18\textwidth}}{col}{{0.38\textwidth}}"
        rf"{col}{{0.38\textwidth}}@{{}}}}",
        r"\toprule",
        f"Stage & Question {labels[0]} & Question {labels[1]} \\\\",
        r"\midrule",
    ]
    for stage, nodes in (stages or FLOW_STAGES):
        cells = []
        for label in labels:
            parts = []
            for node, upd in flow_writes[label]:
                if node not in nodes:
                    continue
                if node in AGENTS_BY_ID:
                    cites = upd["agent_findings"][0]["cites"]
                    parts.append(f"{agent_name(node)}: "
                                 + ", ".join(f"{k}={v}" for k, v in cites.items()))
                else:
                    parts.append(describe_write(node, upd))
            cells.append(latex_escape("; ".join(parts)) or "--")
        lines.append(f"{latex_escape(stage)} & {cells[0]} & {cells[1]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(lines, path)
